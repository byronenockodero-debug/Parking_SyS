/*
frontend/static/js/script.js
------------------------------
It does two unrelated jobs:

  1. autofocusPlateInput()  - cosmetic only, used on the entry/exit pages.
  2. Live slot display      - polls the Flask JSON endpoint /api/slots
                               every few seconds and updates the page
                               in place, so the display never needs a
                               manual refresh.

Nothing here decides parking logic. It only reads JSON that Python
already produced (see logic/parking_lot.py) and reflects it on screen.
*/

document.addEventListener("DOMContentLoaded", function () {
    autofocusPlateInput();
    initLiveDisplay();
    initLiveClock();
});

/**
 * If this page has a #live-clock element (the entry and exit pages),
 * tick it every second with the current date/time. This is purely
 * cosmetic - it lets the driver see exactly what moment will be
 * recorded the instant they submit the form. The timestamp that
 * actually gets saved is always generated by Python on the server
 * (datetime.now() in logic/parking_lot.py), not by this script.
 */
function initLiveClock() {
    const el = document.getElementById("live-clock");
    if (!el) {
        return; // This page has no clock element - nothing to do.
    }

    function tick() {
        const now = new Date();
        el.textContent = now.toLocaleString(undefined, {
            weekday: "short",
            day: "2-digit",
            month: "short",
            hour: "2-digit",
            minute: "2-digit",
            second: "2-digit",
        });
    }

    tick();
    setInterval(tick, 1000);
}

/**
 * Put the cursor straight into the plate number field, if the current
 * page has one, so the user can start typing right away.
 */
function autofocusPlateInput() {
    const plateInput = document.getElementById("plate");
    if (plateInput) {
        plateInput.focus();
    }
}

/**
 * If this page has a slot grid (i.e. we're on the Live Display page),
 * start polling the backend every few seconds and refresh the numbers
 * and slot cards without reloading the page.
 */
function initLiveDisplay() {
    const grid = document.getElementById("slot-grid");
    if (!grid) {
        return; // Not the display page - nothing to do here.
    }

    const REFRESH_MS = 4000;
    let lastFetchedAt = Date.now();

    // Refresh the "Updated Xs ago" text every second, independently of
    // how often we actually re-fetch data from the server.
    setInterval(() => updateRelativeTime(lastFetchedAt), 1000);

    async function poll() {
        try {
            const response = await fetch("/api/slots");
            if (!response.ok) {
                throw new Error("Bad response from server");
            }
            const data = await response.json();
            applyUpdate(data);
            lastFetchedAt = Date.now();
            updateRelativeTime(lastFetchedAt);
        } catch (err) {
            // If the request fails (e.g. server briefly restarting),
            // just try again on the next interval - no need to alarm
            // the user over one missed refresh.
            console.warn("Live display refresh failed:", err);
        }
    }

    setInterval(poll, REFRESH_MS);
}

/**
 * Update the stat cards and slot grid to match the latest data from
 * the server, animating only the slots whose status actually changed.
 */
function applyUpdate(data) {
    document.getElementById("free-count").textContent = data.free_count;
    document.getElementById("total-slots").textContent = data.total_slots;
    document.getElementById("waiting-count").textContent = data.waiting_count;

    const waitingCard = document.getElementById("waiting-card");
    waitingCard.classList.toggle("has-waiting", data.waiting_count > 0);

    const grid = document.getElementById("slot-grid");

    data.slots.forEach((slot) => {
        const card = grid.querySelector(`[data-slot-id="${slot.slot_id}"]`);
        if (!card) return;

        const wasOccupied = card.dataset.occupied === "true";
        if (wasOccupied === slot.occupied) {
            return; // No change for this slot - leave it alone.
        }

        // Status changed since the last poll - update the card's
        // content and briefly flash it so the change is noticeable.
        card.dataset.occupied = slot.occupied;
        card.classList.toggle("occupied", slot.occupied);
        card.classList.toggle("free", !slot.occupied);

        card.querySelector(".slot-icon").textContent = slot.occupied ? "\uD83D\uDE97" : "\u2713";
        card.querySelector(".slot-label").textContent = slot.occupied ? slot.plate : "Available";

        card.classList.remove("just-changed");
        // Force a reflow so the animation can be re-triggered even if
        // the class was already removed and re-added quickly.
        void card.offsetWidth;
        card.classList.add("just-changed");
    });
}

/**
 * Show a friendly "Updated just now / Xs ago" string next to the
 * live indicator dot.
 */
function updateRelativeTime(sinceTimestamp) {
    const el = document.getElementById("last-updated");
    if (!el) return;

    const seconds = Math.round((Date.now() - sinceTimestamp) / 1000);
    el.textContent = seconds < 2 ? "Updated just now" : `Updated ${seconds}s ago`;
}
